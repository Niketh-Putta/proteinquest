def row(
    name: str,
    portion: str,
    protein: float,
    calories: float,
    grams: float | None = None,
    aliases: list[str] | None = None,
) -> tuple:
    return (name, portion, protein, calories, grams, aliases)


def existing_names() -> set[str]:
    names: set[str] = set()
    for p in sorted(LIB.glob("food-catalog*.ts")):
        if p.name == "food-catalog-more-5.ts":
            continue
        text = p.read_text()
        for m in re.finditer(r"f\(\s*['\"]([^'\"]+)['\"]", text):
            names.add(m.group(1).strip().lower())
        for m in re.finditer(r"name:\s*['\"]([^'\"]+)['\"]", text):
            names.add(m.group(1).strip().lower())
    return names


def emit(entries: list[tuple]) -> str:
    seen: set[str] = set()
    uniq: list[tuple] = []
    for e in entries:
        key = e[0].strip().lower()
        if not key or key in seen:
            continue
        seen.add(key)
        uniq.append(e)

    lines = [
        "import type { CatalogFood } from './food-catalog';",
        "",
        "function f(",
        "  name: string,",
        "  portion: string,",
        "  protein_g: number,",
        "  calories_g: number,",
        "  estimated_grams?: number,",
        "  aliases?: string[],",
        "): CatalogFood {",
        "  return { name, portion, protein_g, calories_g, estimated_grams, aliases };",
        "}",
        "",
        "/**",
        " * Sixth large add-on catalog: ready meals, whole-serving restaurant dishes,",
        " * regional plates, packaged staples, and everyday ingredients people log",
        " * directly from Add Ingredient search.",
        " */",
        "export const MORE_FOODS_5: CatalogFood[] = [",
    ]
    for name, portion, protein, calories, grams, aliases in uniq:
        args = [repr(name), repr(portion), _num(protein), _num(calories)]
        if grams is not None or aliases:
            args.append(_num(grams) if grams is not None else "undefined")
        if aliases:
            alias_lit = "[" + ", ".join(repr(a) for a in aliases) + "]"
            args.append(alias_lit)
        lines.append(f"  f({', '.join(args)}),")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def _num(v: float | None) -> str:
    if v is None:
        return "undefined"
    if float(v).is_integer():
        return str(int(v))
    return str(v)


