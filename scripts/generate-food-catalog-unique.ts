function existingNames(): Set<string> {
  const names = new Set<string>();
  const norm = (s: string) =>
    s
      .trim()
      .toLowerCase()
      .replace(/[&']/g, '')
      .replace(/[-_/.,+()]/g, ' ')
      .replace(/\s+/g, ' ');
  for (const file of readdirSync(lib)) {
    if (!file.startsWith('food-catalog') || !file.endsWith('.ts')) continue;
    const src = readFileSync(path.join(lib, file), 'utf8');
    for (const m of src.matchAll(/name:\s*['"]([^'"]+)['"]/g)) names.add(norm(m[1]));
    for (const m of src.matchAll(/\bf\(\s*['"]([^'"]+)['"]/g)) names.add(norm(m[1]));
  }
  return names;
}

