function parseRow(row: (string | number | string[])[]): Entry {
  const [name, portion, protein_g, calories_g, estimated_grams, ...rest] = row;
  const aliases = rest.flat().filter((x): x is string => typeof x === 'string');
  return {
    name: String(name),
    portion: String(portion),
    protein_g: Number(protein_g),
    calories_g: Number(calories_g),
    estimated_grams: estimated_grams != null ? Number(estimated_grams) : undefined,
    aliases: aliases.length ? aliases : undefined,
  };
}

function main() {
  const existing = existingNames();
  const entries: Entry[] = [];
  const skipped: string[] = [];

  for (const row of RAW) {
    const e = parseRow(row);
    const key = e.name.trim().toLowerCase().replace(/\s+/g, ' ');
    if (existing.has(key)) {
      skipped.push(e.name);
      continue;
    }
    existing.add(key);
    entries.push(e);
  }

  const lines = entries.map((e) => {
    const parts = [
      `f('${e.name.replace(/'/g, "\\'")}', '${e.portion.replace(/'/g, "\\'")}', ${e.protein_g}, ${e.calories_g}, ${e.estimated_grams ?? 'undefined'}`,
    ];
    if (e.aliases?.length) {
      parts[0] += `, [${e.aliases.map((a) => `'${a.replace(/'/g, "\\'")}'`).join(', ')}]`;
    }
    parts[0] += '),';
    return `  ${parts[0]}`;
  });

  const out = `import type { CatalogFood } from './food-catalog';

function f(
  name: string,
  portion: string,
  protein_g: number,
  calories_g: number,
  estimated_grams?: number,
  aliases?: string[],
): CatalogFood {
  return { name, portion, protein_g, calories_g, estimated_grams, aliases };
}

/**
 * Culinary accents, zests, pastes, spices, and small-portion ingredients
 * people search for when building recipes — missing from fruit/dish entries.
 */
export const UNIQUE_FOODS: CatalogFood[] = [
${lines.join('\n')}
];
`;

  const outPath = path.join(lib, 'food-catalog-unique.ts');
  writeFileSync(outPath, out);
  console.log(`Wrote ${entries.length} entries to ${outPath}`);
  console.log(`Skipped ${skipped.length} duplicates: ${skipped.slice(0, 15).join(', ')}${skipped.length > 15 ? '...' : ''}`);
}

main();
